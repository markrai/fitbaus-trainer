internal object CaptionPreference {
    fun preferred(tracks: List<CaptionTrack>): CaptionTrack? =
        tracks.minWithOrNull(
            compareBy<CaptionTrack>(
                { when {
                    it.languageTag.equals("en", ignoreCase = true) -> 0
                    it.languageTag.startsWith("en-", ignoreCase = true) -> 1
                    else -> 2
                } },
                { it.autoGenerated },
                { it.languageTag },
            ),
        )
}

