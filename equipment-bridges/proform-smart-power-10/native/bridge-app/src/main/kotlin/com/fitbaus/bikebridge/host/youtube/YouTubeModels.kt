internal object YouTubeIds {
    private val ID = Regex("^[A-Za-z0-9_-]{11}$")

    fun isValid(id: String?): Boolean = id != null && ID.matches(id)

    fun thumbnail(id: String): String = "https://i.ytimg.com/vi/$id/mqdefault.jpg"
}

internal object YouTubeFormat {
    fun duration(seconds: Long): String {
        if (seconds <= 0) return ""
        val h = seconds / 3600
        val m = (seconds % 3600) / 60
        val s = seconds % 60
        return if (h > 0) String.format(java.util.Locale.US, "%d:%02d:%02d", h, m, s) else String.format(java.util.Locale.US, "%d:%02d", m, s)
    }

    fun clock(ms: Long): String {
        val seconds = if (ms <= 0) 0 else ms / 1000
        return duration(seconds).ifEmpty { "0:00" }
    }

    fun views(count: Long): String = when {
        count < 0 -> ""
        count >= 1_000_000_000 -> String.format(java.util.Locale.US, "%.1fB views", count / 1_000_000_000.0)
        count >= 1_000_000 -> String.format(java.util.Locale.US, "%.1fM views", count / 1_000_000.0)
        count >= 1_000 -> String.format(java.util.Locale.US, "%.1fK views", count / 1_000.0)
        count == 1L -> "1 view"
        else -> "$count views"
    }

    fun publicationTimestamp(iso8601: String?): Long? {
        val value = iso8601?.trim()?.takeIf { it.isNotEmpty() && it.length <= 40 } ?: return null
        return runCatching { Instant.parse(value).epochSecond }
            .recoverCatching { OffsetDateTime.parse(value).toEpochSecond() }
            .getOrNull()
            ?.takeIf { it > 0 }
    }

    fun age(publishedAtEpochSeconds: Long?, nowEpochSeconds: Long = System.currentTimeMillis() / 1000): String {
        val published = publishedAtEpochSeconds ?: return ""
        if (published <= 0 || published > nowEpochSeconds) return ""
        val elapsed = nowEpochSeconds - published
        if (elapsed < 60) return "just now"
        if (elapsed < 3600) {
            val minutes = elapsed / 60
            return if (minutes == 1L) "1 min ago" else "$minutes mins ago"
        }
        if (elapsed < 86_400) {
            val hours = elapsed / 3600
            return if (hours == 1L) "1 hr ago" else "$hours hrs ago"
        }
        val days = elapsed / 86_400
        val dates = runCatching {
            Pair(Instant.ofEpochSecond(published).atOffset(ZoneOffset.UTC),
                Instant.ofEpochSecond(nowEpochSeconds).atOffset(ZoneOffset.UTC))
        }.getOrNull() ?: return ""
        val years = ChronoUnit.YEARS.between(dates.first, dates.second)
        if (years > 0) return if (years == 1L) "1 yr ago" else "$years yrs ago"
        val months = ChronoUnit.MONTHS.between(dates.first, dates.second)
        if (months > 0) return if (months == 1L) "1 month ago" else "$months months ago"
        return if (days == 1L) "1 day ago" else "$days days ago"
    }

    fun previewMeta(video: VideoSummary, nowEpochSeconds: Long = System.currentTimeMillis() / 1000): String {
        val parts = ArrayList<String>(3)
        video.channel?.takeIf { it.isNotBlank() }?.let { parts += it }
        views(video.viewCount).takeIf { it.isNotEmpty() }?.let { parts += it }
        if (!video.live) age(video.publishedAtEpochSeconds, nowEpochSeconds).takeIf { it.isNotEmpty() }?.let { parts += it }
        return parts.joinToString("  ·  ")
    }

    fun meta(video: VideoSummary): String {
        val parts = ArrayList<String>(3)
        if (!video.channel.isNullOrBlank()) parts += video.channel
        if (video.live) parts += "LIVE" else duration(video.durationSeconds).takeIf { it.isNotEmpty() }?.let { parts += it }
        views(video.viewCount).takeIf { it.isNotEmpty() }?.let { parts += it }
        return parts.joinToString("  ·  ")
    }

    fun qualityUnavailable(maxHeight: Int, lowestHeight: Int?): String =
        if (lowestHeight != null) {
            "This video isn't available at ${maxHeight}p or lower (lowest is ${lowestHeight}p). Raise the maximum quality to play it."
        } else {
            "This video isn't available at ${maxHeight}p or lower. Raise the maximum quality to play it."
        }

    fun failure(kind: FailureKind): String = when (kind) {
        FailureKind.Network -> "Network problem. Check the console's internet connection and try again."
        FailureKind.RateLimited -> "YouTube is temporarily limiting requests from this console. Try again in a few minutes."
        FailureKind.Unavailable -> "This video is unavailable."
        FailureKind.Restricted -> "This video is restricted and cannot be played here."
        FailureKind.Unsupported -> "This video has no format this console can play."
        FailureKind.Extraction -> "YouTube returned something unexpected. Try again, or choose another video."
        FailureKind.Authentication -> "Google authorization is unavailable. Open MY YOUTUBE and sign in again."
    }
}
