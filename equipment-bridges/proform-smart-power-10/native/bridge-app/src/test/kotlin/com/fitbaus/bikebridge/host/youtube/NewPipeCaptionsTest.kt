package com.fitbaus.bikebridge.host.youtube

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream

class NewPipeCaptionsTest {
    private fun stream(url: String, language: String, format: MediaFormat, isUrl: Boolean = true, auto: Boolean = false): SubtitlesStream =
        SubtitlesStream.Builder()
            .setContent(url, isUrl)
            .setMediaFormat(format)
            .setLanguageCode(language)
            .setAutoGenerated(auto)
            .build()

    @Test
    fun mapsSupportedFormatsAndPrefersHumanAuthoredEnglish() {
        val subtitles = listOf(
            stream("https://www.youtube.com/api/timedtext?lang=es", "es", MediaFormat.TTML),
            stream("https://www.youtube.com/api/timedtext?lang=en&auto=1", "en", MediaFormat.VTT, auto = true),
            stream("https://www.youtube.com/api/timedtext?lang=en", "en", MediaFormat.VTT),
        )
        val supported = NewPipeCaptions.supported(subtitles)
        assertEquals(3, supported.size)
        assertEquals("application/ttml+xml", supported.first().mimeType)
        assertEquals("text/vtt", supported.last().mimeType)
        assertEquals("https://www.youtube.com/api/timedtext?lang=en", CaptionPreference.preferred(supported)?.url)
    }

    @Test
    fun rejectsUnsafeOrUnsupportedSubtitleSources() {
        val subtitles = listOf(
            stream("http://www.youtube.com/api/timedtext", "en", MediaFormat.VTT),
            stream("not-a-url", "en", MediaFormat.VTT, isUrl = false),
            stream("https://www.youtube.com/api/timedtext", "en", MediaFormat.TRANSCRIPT3),
            stream("https://www.youtube.com/api/timedtext?lang=en", "en", MediaFormat.SRT),
        )
        val supported = NewPipeCaptions.supported(subtitles)
        assertEquals(1, supported.size)
        assertEquals("application/x-subrip", supported.single().mimeType)
        assertTrue(supported.single().url.startsWith("https://"))
    }
}
